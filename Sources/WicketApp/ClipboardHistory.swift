import AppKit
import CryptoKit
import Observation
import os

/// The pasteboard as the history sees it, so tests can stand in for the system one.
@MainActor protocol PasteboardAccess: AnyObject {
  var changeCount: Int { get }
  var types: [NSPasteboard.PasteboardType]? { get }
  var accessBehavior: NSPasteboard.AccessBehavior { get }
  func string(forType type: NSPasteboard.PasteboardType) -> String?
  func data(forType type: NSPasteboard.PasteboardType) -> Data?
  @discardableResult func declareTypes(_ newTypes: [NSPasteboard.PasteboardType], owner newOwner: Any?) -> Int
  @discardableResult func setData(_ data: Data?, forType dataType: NSPasteboard.PasteboardType) -> Bool
}
extension NSPasteboard: PasteboardAccess {}

/// The texts and images the user copied, newest first, kept in `clipboard-history.json` in the private folder
/// (`Edition.privateDirectory`), outside the agent's working folder, each image as `<id>.png` beside it. Off
/// until the `clipboard` source is on; while on, it polls the pasteboard's change count, which costs no read
/// of the contents, and reads the text, or an image when there is none, only after a change. Never logs what
/// was copied.
@MainActor @Observable
final class ClipboardHistory: HostCommand {
  let id = "clipboard"
  struct Clip: Codable, Equatable, Sendable {
    /// A copied image, whose PNG is `<id>.png` beside the list; the list holds only its size and digest.
    struct Image: Codable, Equatable, Sendable {
      let width: Int
      let height: Int
      let bytes: Int
      let sha256: String
    }
    let id: String
    /// Empty for an image.
    let text: String
    let copied: Date
    /// Present for an image; a file written before images has none and is a text.
    var image: Image? = nil
  }
  /// Items that password managers and other apps mark as not for history (nspasteboard.org).
  nonisolated static let skipped: [NSPasteboard.PasteboardType] = [
    Pasteboard.concealedType, NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
    NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"),
  ]
  nonisolated static let title = "Clipboard"
  nonisolated static let row = Ranking.host(
    "clipboard", title, icon: "doc.on.clipboard", keywords: ["pasteboard"])
  /// The view lists at most this many matches, newest first; typing finds older ones.
  nonisolated static let maxRows = 100
  /// Longer texts are not kept, so one copied log cannot bloat the file and memory.
  nonisolated static let maxBytes = 256 * 1024
  /// Retention: the newest this many, for this long.
  nonisolated static let maxEntries = 500
  nonisolated static let maxDays = 30
  /// Images: one larger PNG is not kept, and past the total the oldest images go first.
  nonisolated static let imageLimits = (each: 10_000_000, total: 200_000_000)

  private(set) var clips: [Clip]
  private(set) var enabled = false
  private let pasteboard: any PasteboardAccess
  private let url: URL
  private let folder: URL
  private let imageLimits: (each: Int, total: Int)
  private let interval: Duration?
  private let writer: LatestWriter<[Clip]>
  private var lastChange: Int?
  private var polling: Task<Void, Never>?
  nonisolated private static let log = Logger(subsystem: "app.wicket", category: "clipboard")

  /// `interval` nil never polls on its own; tests call `poll()`. An image entry whose file is gone is dropped,
  /// and a stray `<uuid>.png` that no entry names is deleted, which a quit between the two writes leaves,
  /// unless a list that could not be read was moved aside (`PrivateList.read`): it may name any image.
  init(
    url: URL, pasteboard: any PasteboardAccess = NSPasteboard.general,
    interval: Duration? = .milliseconds(500), imageLimits: (each: Int, total: Int) = imageLimits
  ) {
    self.pasteboard = pasteboard
    self.interval = interval
    self.imageLimits = imageLimits
    self.url = url
    folder = url.deletingLastPathComponent()
    writer = PrivateList.writer(url, log: Self.log)
    let stored: [Clip]? = PrivateList.read(url)
    let files = Set((try? FileManager.default.contentsOfDirectory(atPath: folder.path)) ?? [])
    clips = (stored ?? []).filter { $0.image == nil || files.contains($0.id + ".png") }
    let named = Set(clips.map { $0.id + ".png" })
    let sweeps = stored != nil && !PrivateList.hasUnreadable(url, among: files)
    for name in files where sweeps && name.hasSuffix(".png") && !named.contains(name) {
      guard UUID(uuidString: String(name.dropLast(4))) != nil else { continue }
      try? FileManager.default.removeItem(at: folder.appending(path: name))
    }
    if clips.count != stored?.count ?? 0 { save() }
  }

  /// Applies the `clipboard` source's switch: starts or stops watching and expires old clips.
  func configure(enabled: Bool, now: Date = Date()) {
    self.enabled = enabled
    if enabled {
      if lastChange == nil { lastChange = pasteboard.changeCount }
      if polling == nil, let interval {
        polling = Task { [weak self] in
          while (try? await Task.sleep(for: interval, tolerance: interval / 2)) != nil {
            guard let self else { return }
            poll()
          }
        }
      }
    } else {
      polling?.cancel()
      polling = nil
      lastChange = nil
    }
    expire(now: now)
  }

  /// Whether macOS lets Wicket read the pasteboard without asking each time.
  var readable: Bool { [.default, .alwaysAllow].contains(pasteboard.accessBehavior) }

  /// Reads the pasteboard once if it changed since the last look. Only the bytes are read here: an image's
  /// decoding, conversion, digest and file write run off the main actor (`capture(image:)`).
  func poll(now: Date = Date()) {
    guard enabled else { return }
    expire(now: now)
    let count = pasteboard.changeCount
    guard count != lastChange else { return }
    lastChange = count
    // Another write replaced Wicket's image, so its TIFF is no longer promised.
    if tiffPromise?.change != count { tiffPromise = nil }
    let started = ContinuousClock.now
    guard readable, let types = pasteboard.types, !types.contains(where: Self.skipped.contains) else {
      return
    }
    // A blank text beside an image, as some apps write, is the image.
    if let text = pasteboard.string(forType: .string), !text.allSatisfy(\.isWhitespace) {
      capture(text, now: now)
    } else if types.contains(.png), let png = pasteboard.data(forType: .png), png.count <= imageLimits.each {
      capturing(png, now: now)
    } else if types.contains(.tiff), let tiff = pasteboard.data(forType: .tiff),
      // Uncompressed TIFF is several times its PNG; far larger would not fit anyway.
      tiff.count <= imageLimits.each * 8
    {
      capturing(tiff, now: now)
    } else {
      return
    }
    Self.log.debug("clipboard: read in \(ContinuousClock.now - started, privacy: .public)")
  }

  /// Adds a copied text on top; copying it again moves the existing clip there.
  func capture(_ text: String, now: Date = Date()) {
    guard !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty, text.utf8.count <= Self.maxBytes
    else { return }
    var next = clips
    let previous = next.firstIndex { $0.image == nil && $0.text == text }.map { next.remove(at: $0) }
    next.insert(Clip(id: previous?.id ?? UUID().uuidString, text: text, copied: now), at: 0)
    replace(with: next)
    expire(now: now)
  }

  /// Images being captured, one after another, so the second of two quick copies sees the first.
  private var capturingImages: Task<Void, Never>?

  /// Clear History is counted when the bytes are read, so one waiting here when it runs never comes.
  private func capturing(_ data: Data, now: Date) {
    let (previous, cleared) = (capturingImages, clears)
    capturingImages = Task { [weak self] in
      await previous?.value
      await self?.capture(image: data, now: now, cleared: cleared)
    }
  }

  /// Waits for the images copied so far to be in the list.
  func captured() async { await capturingImages?.value }

  /// An image as PNG with its pixel size and digest: a PNG as it is, a TIFF converted. Nil when it does not
  /// decode or its PNG is over `limit`.
  nonisolated private static func prepare(_ data: Data, limit: Int) -> (
    png: Data, width: Int, height: Int, sha256: String
  )? {
    guard let bitmap = NSBitmapImageRep(data: data) else { return nil }
    let isPNG = data.starts(with: [0x89, 0x50, 0x4E, 0x47])
    guard let png = isPNG ? data : bitmap.representation(using: .png, properties: [:]), png.count <= limit
    else { return nil }
    let digest = SHA256.hash(data: png).map { String(format: "%02x", $0) }.joined()
    return (png, bitmap.pixelsWide, bitmap.pixelsHigh, digest)
  }

  /// Adds a copied image (PNG or TIFF) where its copy time puts it, normally the top, written as `<id>.png`
  /// (atomically, in the 0700 folder) before its entry; the same PNG bytes again move the existing clip.
  /// Past the total limit the oldest images go. Decoding, converting, hashing and writing run off the main
  /// actor, so a large copy never stalls the panel. `cleared` is the Clear History count when it was copied,
  /// by default now.
  func capture(image data: Data, now: Date = Date(), cleared: Int? = nil) async {
    let (limit, cleared) = (imageLimits.each, cleared ?? clears)
    // A Clear History while it was prepared or written means it never comes.
    guard let image = await Task.detached(operation: { Self.prepare(data, limit: limit) }).value,
      clears == cleared
    else { return }
    var id = clips.first { $0.image?.sha256 == image.sha256 }?.id ?? ""
    if id.isEmpty {
      id = UUID().uuidString
      let (folder, url, png) = (folder, imageURL(id), image.png)
      let saved = await Task.detached {
        do {
          try FileManager.default.createDirectory(
            at: folder, withIntermediateDirectories: true, attributes: [.posixPermissions: 0o700])
          try png.write(to: url, options: .atomic)
          return true
        } catch {
          Self.log.error("image save failed, code \((error as NSError).code, privacy: .public)")
          return false
        }
      }.value
      guard saved else { return }
      // Switched off or cleared while it was written: the file goes, as its entry never comes.
      guard enabled, clears == cleared else {
        try? FileManager.default.removeItem(at: url)
        return
      }
    }
    var next = clips.filter { $0.id != id }
    let entry = Clip.Image(
      width: image.width, height: image.height, bytes: image.png.count, sha256: image.sha256)
    // A text copied while this image was prepared stays above it.
    next.insert(
      Clip(id: id, text: "", copied: now, image: entry),
      at: next.firstIndex { $0.copied <= now } ?? next.count)
    // Newest first, so once the running total passes the limit, every older image goes.
    var total = 0
    replace(
      with: next.filter { clip in
        guard let image = clip.image else { return true }
        total += image.bytes
        return total <= imageLimits.total
      })
    expire(now: now)
  }

  /// Puts a kept image on the pasteboard, resolved from its ID when the action runs, so no action carries
  /// image bytes: its PNG at once, and a TIFF promised, converted only if the target asks for it. False
  /// when it is no longer kept.
  func write(_ id: String) -> Bool {
    guard clips.contains(where: { $0.id == id && $0.image != nil }),
      let png = try? Data(contentsOf: imageURL(id))
    else { return false }
    // Kept here until the next copy as well, since a pasteboard's owner is not documented to be retained.
    let owner = TIFFPromise(png: png)
    tiffPromise = (owner, pasteboard.declareTypes([.png, .tiff], owner: owner))
    pasteboard.setData(png, forType: .png)
    return true
  }
  private var tiffPromise: (owner: TIFFPromise, change: Int)?

  /// The TIFF of a written image, for apps that read only TIFF, made when one asks.
  final class TIFFPromise: NSObject, NSPasteboardTypeOwner, Sendable {
    let png: Data
    init(png: Data) { self.png = png }
    var tiff: Data? { NSBitmapImageRep(data: png)?.tiffRepresentation }
    func pasteboard(_ sender: NSPasteboard, provideDataForType type: NSPasteboard.PasteboardType) {
      if type == .tiff, let tiff { sender.setData(tiff, forType: .tiff) }
    }
  }

  /// Whether Clear History has anything to erase: clips, or a list moved aside as unreadable.
  var canClear: Bool { !clips.isEmpty || PrivateList.hasUnreadable(url) }

  /// The bytes the kept images take on disk.
  var imageBytes: Int { clips.reduce(0) { $0 + ($1.image?.bytes ?? 0) } }

  func delete(_ id: String) { replace(with: clips.filter { $0.id != id }) }

  /// Counts Clear History, so an image still being prepared from before it is dropped.
  private var clears = 0
  /// Also deletes a list moved aside as unreadable and the images kept for it, which are then every
  /// `<uuid>.png` left.
  func clear() {
    clears += 1
    replace(with: [])
    PrivateList.removeUnreadable(url)
    for name in (try? FileManager.default.contentsOfDirectory(atPath: folder.path)) ?? []
    where name.hasSuffix(".png") && UUID(uuidString: String(name.dropLast(4))) != nil {
      try? FileManager.default.removeItem(at: folder.appending(path: name))
    }
  }

  private func imageURL(_ id: String) -> URL { folder.appending(path: id + ".png") }

  /// The one way the list changes: images no longer in it lose their files, and the list is saved.
  private func replace(with next: [Clip]) {
    let kept = Set(next.lazy.filter { $0.image != nil }.map(\.id))
    for clip in clips where clip.image != nil && !kept.contains(clip.id) {
      try? FileManager.default.removeItem(at: imageURL(clip.id))
    }
    clips = next
    save()
  }

  /// Drops what is over `maxEntries` or older than `maxDays`. Cheap when nothing expired, since the
  /// oldest clip is last, so it runs on every poll, on each configuration (at launch, also while off) and
  /// whenever the panel opens.
  func expire(now: Date = Date()) {
    guard
      let kept = PrivateList.retained(
        clips, count: Self.maxEntries, days: Self.maxDays, date: \.copied, now: now)
    else { return }
    replace(with: kept)
  }

  private func save() { writer.submit(clips) }

  /// The command behind the reserved address `clipboard`, answered like an extension's: the input
  /// filters, and a submitted `{"delete": id}` deletes that clip first, as a row's Delete asks.
  func view(for request: ProviderRequest) -> ProviderView {
    if request.submitted, request.action == "delete", let id = request.fields["id"] { delete(id) }
    return ProviderView(items: rows(matching: request.input))
  }
  /// Available while its source is on.
  nonisolated static func isAvailable(in configuration: Configuration, extensions: [String]) -> Bool {
    configuration.isEnabled(row.provider, extensions: extensions)
  }

  /// The rows for the clipboard view: newest first, each word of the input somewhere in the text (an image's
  /// title for an image), ignoring case and diacritics. Return pastes, and the clip can also be copied or
  /// deleted; an image's copy and paste name it by ID. Each row's detail, shown beside the list, is the
  /// text as a literal code block or the image, with quiet properties.
  func rows(matching input: String, now: Date = Date()) -> [Row] {
    expire(now: now)
    let words = input.split(whereSeparator: \.isWhitespace).map(String.init)
    let ages = RelativeDateTimeFormatter()
    ages.unitsStyle = .abbreviated
    ages.dateTimeStyle = .named
    let matches = clips.lazy.filter { clip in
      let text = clip.image.map(Self.title) ?? clip.text
      return words.allSatisfy { text.localizedStandardContains($0) }
    }
    return matches.prefix(Self.maxRows).map { clip in
      let age = ages.localizedString(for: clip.copied, relativeTo: now)
      let delete = RowAction.run(Address(fields: ["id": clip.id], action: "delete"), title: "Delete")
      if let image = clip.image {
        let size = ByteCountFormatter.string(fromByteCount: Int64(image.bytes), countStyle: .file)
        return Row(
          id: clip.id, title: Self.title(image), subtitle: "\(age) · \(size)", icon: "photo",
          actions: [RowAction(.clip(clip.id, paste: true)), RowAction(.clip(clip.id, paste: false)), delete],
          detail: Self.properties([
            ("Dimensions", "\(image.width)×\(image.height)"), ("File size", size), ("Copied", age),
          ]), picture: imageURL(clip.id))
      }
      // The first nonblank line with spaces collapsed, and the line count.
      let title = clip.text.drop { $0.isWhitespace }.prefix { !$0.isNewline }.prefix(300)
        .split(whereSeparator: \.isWhitespace).joined(separator: " ")
      let lines = clip.text.utf8.reduce(1) { $0 + ($1 == 10 ? 1 : 0) }
      return Row(
        id: clip.id, title: title, subtitle: lines > 1 ? "\(age) · \(lines) lines" : age,
        icon: "doc.on.clipboard",
        actions: [.paste(clip.text), .copy(clip.text), delete],
        detail: Self.detail(clip.text, lines: lines, age: age))
    }
  }

  /// The detail shows at most this much of a text: enough to recognize it, and cheap to build for every
  /// row and to draw on each arrow key.
  nonisolated static let detailLimit = (bytes: 5000, lines: 200)

  /// A text as a literal code block, its fence longer than any run of backticks in it, so nothing in it is
  /// read as Markdown or a tag, then its properties. One pass over the bytes shown, since every row of the
  /// view builds one.
  nonisolated static func detail(_ text: String, lines: Int, age: String) -> String {
    let bytes = text.utf8
    var end = bytes.startIndex
    var newlines = 0
    var run = 0
    var longest = 0
    for byte in bytes.prefix(detailLimit.bytes) {
      if byte == 10 {
        newlines += 1
        if newlines == detailLimit.lines { break }
      }
      run = byte == 96 ? run + 1 : 0
      longest = max(longest, run)
      bytes.formIndex(after: &end)
    }
    // Never into the middle of a character's bytes.
    while end < bytes.endIndex, UTF8.isContinuation(bytes[end]) { bytes.formIndex(before: &end) }
    let fence = String(repeating: "`", count: max(3, longest + 1))
    let more = end < bytes.endIndex ? "\n\nShows the beginning; Return pastes all of it." : ""
    return "\(fence)\n\(text[..<end])\n\(fence)\(more)\n\n"
      + properties([
        ("Copied", age), ("Lines", count(lines)), ("Characters", count(text.count)),
      ])
  }
  nonisolated private static func count(_ value: Int) -> String {
    value.formatted(IntegerFormatStyle<Int>(locale: .autoupdatingCurrent))
  }

  /// Label and value pairs as property rows, quiet lines on the page.
  nonisolated private static func properties(_ pairs: [(String, String)]) -> String {
    pairs.map { "<row label=\"\($0)\" value=\"\($1)\"/>" }.joined(separator: "\n")
  }

  nonisolated static func title(_ image: Clip.Image) -> String { "Image \(image.width)×\(image.height)" }

  func finish() async {
    polling?.cancel()
    await captured()
    await writer.finish()
  }
}
