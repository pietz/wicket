/// The pasteboard edge: what the history would read from the system one.
@MainActor final class FakePasteboard: PasteboardAccess {
  var changeCount = 0
  var types: [NSPasteboard.PasteboardType]? = []
  var accessBehavior = NSPasteboard.AccessBehavior.alwaysAllow
  var text: String?
  var reads = 0
  func string(forType type: NSPasteboard.PasteboardType) -> String? {
    reads += 1
    return text
  }
  func copy(_ text: String, marked: [String] = []) {
    changeCount += 1
    self.text = text
    types = [.string] + marked.map { NSPasteboard.PasteboardType($0) }
  }
}

@MainActor private func makeHistory(_ folder: URL, enabled: Bool = true) -> (ClipboardHistory, FakePasteboard)
{
  let pasteboard = FakePasteboard()
  let history = ClipboardHistory(
    url: folder.appending(path: "clipboard-history.json"), pasteboard: pasteboard, interval: nil)
  history.configure(enabled: enabled)
  return (history, pasteboard)
}

private func temporaryFolder() throws -> URL {
  let folder = FileManager.default.temporaryDirectory.appending(path: "wicket-clipboard-" + UUID().uuidString)
  try FileManager.default.createDirectory(at: folder, withIntermediateDirectories: true)
  return folder
}

@MainActor @Test func capturesChangedTextOnlyAndDeduplicatesToTheTop() async throws {
  let folder = try temporaryFolder()
  let (history, pasteboard) = makeHistory(folder)
  pasteboard.copy("first")
  history.poll()
  // No change since the last look: the contents are not read again.
  history.poll()
  #expect(pasteboard.reads == 1)
  pasteboard.copy("second")
  history.poll()
  let firstID = history.clips.last?.id
  pasteboard.copy("first")
  history.poll()
  #expect(history.clips.map(\.text) == ["first", "second"])
  #expect(history.clips.first?.id == firstID)
  // Blank text is not kept.
  pasteboard.copy("  \n")
  history.poll()
  #expect(history.clips.count == 2)
  // Persisted and read back by a new instance.
  await history.finish()
  let url = folder.appending(path: "clipboard-history.json")
  let reloaded = ClipboardHistory(url: url, pasteboard: FakePasteboard(), interval: nil)
  #expect(reloaded.clips.map(\.text) == ["first", "second"])
}

@MainActor @Test func skipsConcealedTransientAndUnreadableCopies() throws {
  let folder = try temporaryFolder()
  for marker in [
    "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
  ] {
    let (history, pasteboard) = makeHistory(folder)
    pasteboard.copy("hunter2", marked: [marker])
    history.poll()
    #expect(history.clips.isEmpty && pasteboard.reads == 0, Comment(rawValue: marker))
  }
  // macOS would ask on every read: nothing is read.
  let (asking, prompted) = makeHistory(folder)
  prompted.accessBehavior = .ask
  prompted.copy("hello")
  asking.poll()
  #expect(asking.clips.isEmpty && prompted.reads == 0 && !asking.readable)
  // Off: nothing is read, and switching on does not take what was already there.
  let (off, idle) = makeHistory(folder, enabled: false)
  idle.copy("before")
  off.poll()
  off.configure(enabled: true)
  off.poll()
  #expect(off.clips.isEmpty && idle.reads == 0)
  // Too long to keep.
  idle.copy(String(repeating: "x", count: ClipboardHistory.maxBytes + 1))
  off.poll()
  #expect(off.clips.isEmpty)
}

@MainActor @Test func savesOwnerOnlyInAPrivateFolder() async throws {
  let url = try temporaryFolder().appending(path: "private/clipboard-history.json")
  let history = ClipboardHistory(url: url, pasteboard: FakePasteboard(), interval: nil)
  history.capture("secret")
  await history.finish()
  let manager = FileManager.default
  let folderMode = try manager.attributesOfItem(atPath: url.deletingLastPathComponent().path)[
    .posixPermissions]
  #expect(folderMode as? Int == 0o700 && manager.fileExists(atPath: url.path))
}

