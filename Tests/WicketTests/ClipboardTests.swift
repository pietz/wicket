@MainActor @Test func expiredClipsGoAtLaunchAndWhenThePanelOpensEvenWhileOff() async throws {
  let folder = try temporaryFolder()
  let url = folder.appending(path: "clipboard-history.json")
  let start = Date(timeIntervalSince1970: 1_000_000)
  let writer = ClipboardHistory(url: url, pasteboard: FakePasteboard(), interval: nil)
  writer.capture("old", now: start)
  writer.capture("new", now: start.addingTimeInterval(10 * 24 * 3600))
  await writer.finish()
  // Launch with the feature off, 35 days on: the configuration prunes, the pasteboard is not read.
  let pasteboard = FakePasteboard()
  let history = ClipboardHistory(url: url, pasteboard: pasteboard, interval: nil)
  history.configure(enabled: false, now: start.addingTimeInterval(35 * 24 * 3600))
  #expect(history.clips.map(\.text) == ["new"] && pasteboard.reads == 0)
  // Idle while off: opening the panel expires the rest.
  let model = LauncherModel(
    providers: [], clipboard: history, history: UsageHistory(url: folder.appending(path: "usage.json")),
    folder: folder)
  model.reopen(now: start.addingTimeInterval(41 * 24 * 3600))
  #expect(history.clips.isEmpty && pasteboard.reads == 0)
  await model.finish()
}

@MainActor @Test func retentionKeepsTheNewestWithinCountAndAge() throws {
  let (history, _) = makeHistory(try temporaryFolder())
  let start = Date(timeIntervalSince1970: 1_000_000)
  let count = ClipboardHistory.maxEntries + 2
  for index in 0..<count {
    history.capture("clip \(index)", now: start.addingTimeInterval(Double(index) * 3600))
  }
  #expect(history.clips.count == ClipboardHistory.maxEntries && history.clips.last?.text == "clip 2")
  // Half an hour past 30 days after the second newest was copied, only the newest is young enough.
  let expiry = Double(ClipboardHistory.maxDays) * 24 * 3600
  let rows = history.rows(
    matching: "", now: start.addingTimeInterval(Double(count - 2) * 3600 + expiry + 1800))
  #expect(rows.map(\.title) == ["clip \(count - 1)"])
}

@MainActor @Test func rowsFilterByEveryWordAndPasteTheExactText() throws {
  let (history, _) = makeHistory(try temporaryFolder())
  history.capture("Grüße aus Berlin\nzweite Zeile")
  history.capture("https://example.com/report")
  history.capture("meeting notes berlin")
  #expect(history.rows(matching: "").map(\.title).first == "meeting notes berlin")
  #expect(history.rows(matching: "BERLIN grusse").map(\.title) == ["Grüße aus Berlin"])
  #expect(history.rows(matching: "berlin notes").map(\.title) == ["meeting notes berlin"])
  let row = try #require(history.rows(matching: "zeile").first)
  #expect(row.subtitle?.hasSuffix("2 lines") == true)
  #expect(
    row.actions == [
      .paste("Grüße aus Berlin\nzweite Zeile"), .copy("Grüße aus Berlin\nzweite Zeile"),
      .run(Address(arguments: ["delete", row.id])),
    ])
  // An extension's paste still loses its newlines when decoded.
  let decoded = try JSONDecoder().decode(RowAction.self, from: Data(#"{"type":"paste","text":"a\nb"}"#.utf8))
  #expect(decoded == .paste("ab"))
}

@MainActor @Test func theHistoryAnswersRequestsLikeAnExtension() async throws {
  let (history, _) = makeHistory(try temporaryFolder())
  history.capture("alpha one")
  history.capture("beta two")
  #expect(
    await history.view(for: ProviderRequest(input: "")).items.map(\.title) == ["beta two", "alpha one"])
  #expect(await history.view(for: ProviderRequest(input: "alp")).items.map(\.title) == ["alpha one"])
  // Delete is the row's own run action, answered with the updated list.
  let alpha = try #require(history.clips.last)
  let view = await history.view(
    for: ProviderRequest(input: "", arguments: ["delete", alpha.id], chosen: true))
  #expect(view.items.map(\.title) == ["beta two"] && history.clips.map(\.text) == ["beta two"])
}

@MainActor @Test func panelOpensTheHistoryFiltersDeletesAndClears() async throws {
  let folder = try temporaryFolder()
  let (history, _) = makeHistory(folder, enabled: false)
  let model = LauncherModel(
    providers: [], clipboard: history, history: UsageHistory(url: folder.appending(path: "usage.json")),
    folder: folder)
  model.store.start(watching: false)
  // Off: no row, and the address opens the command only to say how to switch it on.
  model.input = "clip"
  await model.settled()
  #expect(!model.results.contains { $0.provider == "clipboard" })
  model.go(Address(extensionName: "clipboard"))
  #expect(model.command?.problem?.contains("Switch it on in Settings") == true && model.results.isEmpty)
  #expect(model.escape())

  model.store.update { $0.providers = [.init("clipboard")] }
  history.capture("alpha one")
  history.capture("beta two")
  model.input = "clip"
  await model.settled()
  let row = try #require(model.results.first { $0.provider == "clipboard" })
  model.select(row.id)
  #expect(model.activateReturn())
  await model.settled()
  #expect(model.command?.id == "clipboard" && model.input == "" && model.commandName == "Clipboard History")
  #expect(model.results.map(\.row.title) == ["beta two", "alpha one"])
  #expect(model.returnAction == .paste("beta two"))
  model.input = "alp"
  await model.settled()
  #expect(model.results.map(\.row.title) == ["alpha one"])
  // Delete from the context menu: the row's own run action, through the one dispatcher.
  let alpha = try #require(model.results.first)
  #expect(alpha.row.actions.last?.label == "Delete")
  #expect(model.activate(try #require(alpha.row.actions.last), from: alpha))
  await model.settled()
  #expect(model.command?.id == "clipboard" && model.input == "alp")
  #expect(model.results.isEmpty && history.clips.map(\.text) == ["beta two"])
  #expect(model.escape() && model.command == nil)
  // Clearing empties the view; an outsider's URL opens it with the input filled.
  history.clear()
  model.go(try #require(Address(url: URL(string: "wicket://clipboard?input=beta")!)))
  await model.settled()
  #expect(model.command?.id == "clipboard" && model.input == "beta" && model.results.isEmpty)
  // Switched off while open: the command says how to switch it back on.
  model.store.update { $0.providers = [.init("clipboard", enabled: false)] }
  model.refresh()
  #expect(model.command?.problem?.contains("switched off") == true && model.results.isEmpty)
  await model.finish()
}

@Test func clipboardIsASourceThatDefaultsOff() throws {
  let defaults = try JSONDecoder().decode(Configuration.self, from: Data("{}".utf8))
  #expect(!defaults.isEnabled("clipboard", extensions: []))
  #expect(defaults.sources(extensions: []).contains(.init("clipboard", enabled: false)))
  // A source list written without it leaves it off; its own entry decides.
  let listed = try JSONDecoder().decode(
    Configuration.self, from: Data(#"{"providers":[{"id":"math","enabled":true}]}"#.utf8))
  #expect(!listed.isEnabled("clipboard", extensions: []) && listed.isEnabled("apps", extensions: []))
  let on = try JSONDecoder().decode(
    Configuration.self, from: Data(#"{"providers":[{"id":"clipboard","enabled":true}]}"#.utf8))
  #expect(on.isEnabled("clipboard", extensions: []))
}
