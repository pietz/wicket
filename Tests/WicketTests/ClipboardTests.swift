@MainActor @Test func expiredClipsGoAtLaunchAndWhenThePanelOpensEvenWhileOff() async throws {
  let folder = try temporaryFolder()
  let url = folder.appending(path: "clipboard-history.json")
  let start = Date(timeIntervalSince1970: 1_000_000)
  let writer = ClipboardHistory(url: url, pasteboard: FakePasteboard(), interval: nil)
  writer.capture("old", now: start)
  writer.capture("new", now: start.addingTimeInterval(10 * 24 * 3600))
  await writer.finish()
  // Launch with the feature off and a 5-day limit: the configuration prunes, the pasteboard is not read.
  let pasteboard = FakePasteboard()
  let history = ClipboardHistory(url: url, pasteboard: pasteboard, interval: nil)
  var settings = Configuration.Clipboard()
  settings.maxDays = 5
  history.configure(settings, now: start.addingTimeInterval(11 * 24 * 3600))
  #expect(history.clips.map(\.text) == ["new"] && pasteboard.reads == 0)
  // Idle while off: opening the panel expires the rest.
  let model = LauncherModel(
    providers: [], clipboard: history, history: UsageHistory(url: folder.appending(path: "usage.json")),
    folder: folder)
  model.reopen(now: start.addingTimeInterval(16 * 24 * 3600))
  #expect(history.clips.isEmpty && pasteboard.reads == 0)
  await model.finish()
}

@MainActor @Test func retentionKeepsTheNewestWithinCountAndAge() throws {
  let (history, _) = makeHistory(try temporaryFolder())
  var settings = Configuration.Clipboard()
  settings.enabled = true
  settings.maxEntries = 3
  settings.maxDays = 2
  history.configure(settings)
  let start = Date(timeIntervalSince1970: 1_000_000)
  for index in 0..<5 { history.capture("clip \(index)", now: start.addingTimeInterval(Double(index) * 3600)) }
  #expect(history.clips.map(\.text) == ["clip 4", "clip 3", "clip 2"])
  // Two days after clip 3 was copied, only clip 4 is young enough.
  let rows = history.rows(matching: "", now: start.addingTimeInterval(2 * 24 * 3600 + 3.5 * 3600))
  #expect(rows.map(\.title) == ["clip 4"])
}

@MainActor @Test func rowsFilterByEveryWordAndPasteTheExactText() throws {
  let (history, _) = makeHistory(try temporaryFolder())
  history.capture("Grüße aus Berlin\nzweite Zeile")
  history.capture("https://example.com/report")
  history.capture("meeting notes berlin")
  #expect(history.rows(matching: "").map(\.title).first == "meeting notes berlin")
  #expect(history.rows(matching: "BERLIN grusse").map(\.title) == ["Grüße aus Berlin"])
  #expect(history.rows(matching: "berlin notes").map(\.title) == ["meeting notes berlin"])
  let row = try #require(history.rows(matching: "zeile").first)
  #expect(row.subtitle?.hasSuffix("2 lines") == true)
  #expect(
    row.actions == [
      .paste("Grüße aus Berlin\nzweite Zeile"), .copy("Grüße aus Berlin\nzweite Zeile"), .forget(row.id),
    ])
  // An extension's paste still loses its newlines when decoded.
  let decoded = try JSONDecoder().decode(RowAction.self, from: Data(#"{"type":"paste","text":"a\nb"}"#.utf8))
  #expect(decoded == .paste("ab"))
  // The host's delete action is never decoded.
  #expect(throws: (any Error).self) {
    try JSONDecoder().decode(RowAction.self, from: Data(#"{"type":"forget","id":"x"}"#.utf8))
  }
}

@MainActor @Test func panelOpensTheHistoryFiltersDeletesAndClears() async throws {
  let folder = try temporaryFolder()
  let (history, _) = makeHistory(folder, enabled: false)
  let model = LauncherModel(
    providers: [], clipboard: history, history: UsageHistory(url: folder.appending(path: "usage.json")),
    folder: folder)
  model.store.start(watching: false)
  // Off: no row, and the address only says how to switch it on.
  model.input = "clip"
  await model.settled()
  #expect(!model.results.contains { $0.provider == "clipboard" })
  model.go(Address(extensionName: "clipboard"))
  #expect(model.command == nil && model.problem?.contains("Settings") == true)

  model.store.update { $0.clipboard.enabled = true }
  history.capture("alpha one")
  history.capture("beta two")
  model.input = "clip"
  await model.settled()
  let row = try #require(model.results.first { $0.provider == "clipboard" })
  model.select(row.id)
  #expect(model.activateReturn())
  #expect(model.command?.id == "clipboard" && model.input == "" && model.commandName == "Clipboard History")
  #expect(model.results.map(\.row.title) == ["beta two", "alpha one"])
  #expect(model.returnAction == .paste("beta two"))
  model.input = "alp"
  #expect(model.results.map(\.row.title) == ["alpha one"])
  // Delete from the context menu, through the one dispatcher.
  let alpha = try #require(model.results.first)
  #expect(model.activate(.forget(alpha.row.id), from: alpha))
  #expect(model.results.isEmpty && history.clips.map(\.text) == ["beta two"])
  #expect(model.escape() && model.command == nil)
  // Clearing empties the view; an outsider's URL opens it with the input filled.
  history.clear()
  model.go(try #require(Address(url: URL(string: "wicket://clipboard?input=beta")!)))
  #expect(model.command?.id == "clipboard" && model.input == "beta" && model.results.isEmpty)
  // Switched off while open: back to search.
  model.store.update { $0.clipboard.enabled = false }
  model.refresh()
  #expect(model.command == nil)
  await model.finish()
}

@Test func clipboardSettingsDefaultOffAndValidateLimits() throws {
  let defaults = try JSONDecoder().decode(Configuration.self, from: Data("{}".utf8))
  #expect(
    !defaults.clipboard.enabled && defaults.clipboard.maxEntries == 500 && defaults.clipboard.maxDays == 30)
  #expect(defaults.clipboard.excludedApps.contains("com.apple.Passwords"))
  let custom = try JSONDecoder().decode(
    Configuration.self, from: Data(#"{"clipboard":{"enabled":true,"excludedApps":["a.b"]}}"#.utf8))
  #expect(custom.clipboard.enabled && custom.clipboard.excludedApps == ["a.b"])
  #expect(throws: (any Error).self) {
    try JSONDecoder().decode(Configuration.self, from: Data(#"{"clipboard":{"maxEntries":0}}"#.utf8))
  }
}
